/* Handle input in frequency menu modes */
static void handle_freq_menu_input(uint8_t key) {
    if (key == APP_KEY_INVALID || key == g.prevKey) {
        g.prevKey = key;
        return;
    }
    g.prevKey = key;

    switch (g.edit_mode) {
        case 1: /* SELECT mode */
            if (key == APP_KEY_EXIT) {
                g.edit_mode = 0;
                g.redraw |= REDRAW_ON;
            } else if (key == APP_KEY_UP) {
                if (g.selected_index > 0) {
                    g.selected_index--;
                } else if (g.freq_count > 0) {
                    g.selected_index = g.freq_count - 1;
                }
                g.redraw |= REDRAW_ON;
            } else if (key == APP_KEY_DOWN) {
                if (g.selected_index < g.freq_count - 1) {
                    g.selected_index++;
                } else if (g.freq_count > 0) {
                    g.selected_index = 0;
                }
                g.redraw |= REDRAW_ON;
            } else if (key == APP_KEY_STAR && g.freq_count > 0) {
                /* Apply selected frequency */
                apply_frequency(g.freq_list[g.selected_index].freq_10hz);
                g.edit_mode = 0;
                g.redraw |= REDRAW_FRAME;
            } else if (key == APP_KEY_F) {
                /* Start new frequency entry */
                reset_freq_input();
                reset_desc_input();
                g.edit_mode = 2;
                g.redraw |= REDRAW_ON;
            } else if (key == APP_KEY_2 && g.freq_count > 0) {
                /* Delete selected frequency */
                delete_frequency(g.selected_index);
                g.redraw |= REDRAW_ON;
            } else if (key == APP_KEY_1 && g.list_dirty) {
                /* Save list */
                save_freq_list();
                g.redraw |= REDRAW_ON;
            }
            break;

        case 2: /* EDIT_FREQ mode */
            if (key == APP_KEY_EXIT) {
                g.edit_mode = 1;
                g.redraw |= REDRAW_ON;
            } else if (key == APP_KEY_STAR) {
                /* Validate frequency input */
                uint32_t freq = parse_freq_input();
                if (freq > 0) {
                    /* Switch to description input */
                    g.edit_mode = 3;
                    reset_desc_input();
                    g.desc_cursor = 0;
                    g.redraw |= REDRAW_ON;
                }
            } else if (key >= APP_KEY_0 && key <= APP_KEY_9) {
                /* Add digit */
                if (g.freq_input.len < 9) {
                    g.freq_input.digits[g.freq_input.len] = '0' + key;
                    g.freq_input.len++;
                    g.freq_input.digits[g.freq_input.len] = '\0';
                    g.redraw |= REDRAW_ON;
                }
            } else if (key == APP_KEY_UP) {
                /* Move cursor right */
                if (g.freq_input.pos < g.freq_input.len) {
                    g.freq_input.pos++;
                }
            } else if (key == APP_KEY_DOWN) {
                /* Move cursor left */
                if (g.freq_input.pos > 0) {
                    g.freq_input.pos--;
                }
            }
            break;

        case 3: /* EDIT_DESC mode */
            if (key == APP_KEY_EXIT) {
                g.edit_mode = 2;
                g.redraw |= REDRAW_ON;
            } else if (key == APP_KEY_STAR) {
                /* Save new entry and return to SELECT */
                uint32_t freq = parse_freq_input();
                if (freq > 0) {
                    add_new_frequency(freq, g.desc_input);
                }
                g.edit_mode = 1;
                g.redraw |= REDRAW_ON;
            } else if (key >= APP_KEY_0 && key <= APP_KEY_9) {
                /* Add digit to description */
                if (g.desc_cursor < MAX_DESC_LEN) {
                    g.desc_input[g.desc_cursor] = '0' + key;
                    g.desc_input[g.desc_cursor + 1] = '\0';
                    g.desc_cursor++;
                    g.redraw |= REDRAW_ON;
                }
            } else if (key == APP_KEY_UP) {
                /* Next character */
                cycle_desc_char(true);
                g.redraw |= REDRAW_ON;
            } else if (key == APP_KEY_DOWN) {
                /* Previous character */
                cycle_desc_char(false);
                g.redraw |= REDRAW_ON;
            } else if (key == APP_KEY_F || key == APP_KEY_STAR) {
                /* Move cursor right */
                if (g.desc_cursor < MAX_DESC_LEN) {
                    g.desc_cursor++;
                    if (g.desc_input[g.desc_cursor] == '\0') {
                        g.desc_input[g.desc_cursor] = ' '; /* Auto-fill with space */
                        g.desc_input[g.desc_cursor + 1] = '\0';
                    }
                    g.redraw |= REDRAW_ON;
                }
            }
            break;
    }
}

