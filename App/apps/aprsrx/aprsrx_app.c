/* Apply frequency to VFO by writing BK4829 frequency registers */
static void apply_frequency(uint32_t freq_10hz) {
    const app_api_t *A = g.A;
    A->bk_write(REG_FREQ_LOW, (uint16_t)(freq_10hz));
    A->bk_write(REG_FREQ_HIGH, (uint16_t)(freq_10hz >> 16));
    A->delay_ms(10);
}

/* Parse frequency input buffer (MHz) to 10 Hz units */
static uint32_t parse_freq_input(void) {
    char *p = g.freq_input.digits;
    uint32_t freq_mhz = 0;
    while (*p) {
        if (*p >= '0' && *p <= '9') {
            freq_mhz = freq_mhz * 10 + (*p - '0');
        }
        p++;
    }
    /* Convert MHz to 10 Hz units (e.g., 144.800 -> 144800000) */
    return freq_mhz * 100000u;
}

/* Load frequency list from persistent config */
static void load_freq_list(void) {
    const app_api_t *A = g.A;
    uint8_t version = 0;
    
    /* Try to load config version */
    A->cfg_load(&version, 1);
    
    /* If version doesn't match or list is corrupted, start fresh */
    if (version != FREQ_CONFIG_VERSION) {
        g.freq_count = 0;
        g.list_dirty = false;
        return;
    }
    
    /* Load count */
    A->cfg_load(&g.freq_count, 1);
    if (g.freq_count > MAX_FREQ_ENTRIES) g.freq_count = 0;
    
    /* Load entries */
    if (g.freq_count > 0) {
        A->cfg_load((uint8_t*)g.freq_list, g.freq_count * sizeof(freq_entry_t));
    }
    g.list_dirty = false;
}

/* Save frequency list to persistent config */
static void save_freq_list(void) {
    const app_api_t *A = g.A;
    
    /* Save version */
    uint8_t version = FREQ_CONFIG_VERSION;
    A->cfg_save(&version, 1);
    
    /* Save count */
    A->cfg_save(&g.freq_count, 1);
    
    /* Save entries */
    if (g.freq_count > 0) {
        A->cfg_save((uint8_t*)g.freq_list, g.freq_count * sizeof(freq_entry_t));
    }
    g.list_dirty = false;
}

/* Add new frequency entry to list */
static void add_new_frequency(uint32_t freq_10hz, const char *desc) {
    if (g.freq_count >= MAX_FREQ_ENTRIES) return;
    
    freq_entry_t *entry = &g.freq_list[g.freq_count];
    entry->freq_10hz = freq_10hz;
    strncpy(entry->desc, desc, MAX_DESC_LEN);
    entry->desc[MAX_DESC_LEN] = '\0';
    g.freq_count++;
    g.selected_index = g.freq_count - 1;
    g.list_dirty = true;
}

/* Delete frequency entry from list */
static void delete_frequency(uint8_t index) {
    if (index >= g.freq_count) return;
    
    /* Shift all entries after index down */
    for (uint8_t i = index; i < g.freq_count - 1; i++) {
        g.freq_list[i] = g.freq_list[i + 1];
    }
    g.freq_count--;
    
    /* Adjust selected index */
    if (g.selected_index >= g.freq_count && g.freq_count > 0) {
        g.selected_index = g.freq_count - 1;
    } else if (g.freq_count == 0) {
        g.selected_index = 0;
    }
    g.list_dirty = true;
}

/* Format frequency in 10 Hz units to string (e.g., "144.800") */
static char* format_frequency(char *buf, uint32_t freq_10hz) {
    uint32_t mhz = freq_10hz / 100000u;
    uint32_t khz = (freq_10hz % 100000u) / 1000u;
    
    /* Format MHz part */
    char *o = buf;
    if (mhz == 0) {
        *o++ = '0';
    } else {
        /* Format up to 4 digits for MHz (max 9999 MHz) */
        uint32_t v = mhz;
        if (v >= 1000) { *o++ = '0' + sub(&v, 1000u); }
        if (v >= 100) { *o++ = '0' + sub(&v, 100u); }
        if (v >= 10) { *o++ = '0' + sub(&v, 10u); }
        *o++ = '0' + v;
    }
    
    /* Add decimal point */
    *o++ = '.';
    
    /* Format kHz part with leading zeros (3 digits) */
    uint32_t v = khz;
    if (v >= 100) {
        *o++ = '0' + sub(&v, 100u);
        *o++ = '0' + sub(&v, 10u);
        *o++ = '0' + v;
    } else if (v >= 10) {
        *o++ = '0';
        *o++ = '0' + sub(&v, 10u);
        *o++ = '0' + v;
    } else {
        *o++ = '0';
        *o++ = '0';
        *o++ = '0' + v;
    }
    *o = '\0';
    return buf;
}

/* Character set for description input */
static const char DESC_CHARS[] = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 -/.";

/* Handle description character cycling */
static void cycle_desc_char(bool forward) {
    if (g.desc_cursor >= MAX_DESC_LEN) return;
    
    char current = g.desc_input[g.desc_cursor];
    const char *p = strchr(DESC_CHARS, current);
    int idx;
    
    if (p == NULL) {
        /* Current char not in set, start from beginning */
        idx = 0;
    } else {
        idx = (int)(p - DESC_CHARS);
    }
    
    if (forward) {
        idx = (idx + 1) % (sizeof(DESC_CHARS) - 1);
    } else {
        idx = (idx - 1 + sizeof(DESC_CHARS) - 1) % (sizeof(DESC_CHARS) - 1);
    }
    
    g.desc_input[g.desc_cursor] = DESC_CHARS[idx];
}

/* Reset frequency input buffer */
static void reset_freq_input(void) {
    memset(&g.freq_input, 0, sizeof(g.freq_input));
    g.freq_input.digits[0] = '\0';
    g.freq_input.len = 0;
    g.freq_input.pos = 0;
}

/* Reset description input buffer */
static void reset_desc_input(void) {
    memset(g.desc_input, 0, sizeof(g.desc_input));
    g.desc_input[0] = '\0';
    g.desc_cursor = 0;
}

