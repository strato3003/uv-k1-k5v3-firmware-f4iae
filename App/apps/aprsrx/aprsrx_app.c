/*
 * APRS RX - receives APRS (AX.25 UI frames, Bell 202 AFSK 1200 bauds) in
 * software and keeps the last five frames, shown one at a time: source,
 * destination and path, the info field. Tune the VFO (FM; 144.800 MHz, or 433.650 MHz for the Flipper Zero
 * bench files of test/flipper_aprs.py), then launch.
 *
 * The BK4829 has no Bell 202 demodulator (see README.md), so the RX audio is
 * sampled as EPIRB 406 does: it reaches PA4 (the voice DAC pin), held at
 * mid-scale by the MCU DAC (unbuffered), and is read on ADC channel 4 at
 * 9.6 kHz, timed from SysTick, continuously, as a TNC does: no RSSI gate, the
 * FCS and the UI check sort frames from noise. Each sample goes through the
 * demodulator modelled and tested in test/model_rx.py: band-pass, 1200/2200 Hz
 * sliding correlators over one bit, per-tone AGC, then 3 slicers (mark/space
 * weights 2:3, 1:1, 3:2), each with its DPLL, NRZI, HDLC and FCS. Keep the two
 * in step.
 * Keys and the screen cost sample time (the key scan alone is ~400 us), so they
 * are served every 50 ms only while no slicer is inside a preamble or a
 * plausible frame; the redraw follows a new frame, a key, or every 5 s.
 *
 * Keys (UV-K5 and UV-K1): UP/DOWN (held) scroll the frame 1 px per slot when
 *   needed; pressed again at either end: the newer / older frame · * normal
 *   view / compact view (saved) · 1 speaker on/off (saved, off by default: the
 *   decoder does not need it; while on, the squelch gates it) · 2 clear · EXIT
 *   quit · F frequency menu
 * The loader re-runs RADIO_SetupRegisters on exit; the resident capture
 * (af_capture_close) restores the ADC, PA4, the DAC and its clock.
 */

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include <string.h>
#include "../app_api.h"
#include "aprsrx_assets.h"     /* generated by gen_assets.py */

/* ---- sampling: the PA4 capture and the 48 MHz cycle clock are resident
 * (API level 3); the capture holds PA4 at mid-scale (ADC code 2048). ---- */
#define BIAS_CODE      2048u
#define FS             9600u
#define CYC_PER_SAMPLE (48000000u / FS)            /* 5000 */
#define HOUSE_EVERY    480u    /* samples between key/screen slots (50 ms)       */
#define BUSY_MAX       60u     /* serve them anyway after 60 busy slots (3 s)    */
#define REFRESH_SLOTS  100u    /* 100 housekeeping slots = 5 s (battery redraw) */
#define REDRAW_ON      1u      /* g.redraw: a key or the periodic refresh        */
#define REDRAW_FRAME   2u      /* g.redraw: a new frame, also wakes the backlight */
#define DUP_MS         1000u   /* the same frame from another slicer             */

/* ---- BK4829 ---- */
#define REG_FREQ_LOW   0x38u
#define REG_FREQ_HIGH  0x39u

/* ---- demodulator (test/model_rx.py, class Demod) ---- */
#define BP_B0       5356   /* band-pass 1625 Hz, Q 0.9, Q14 (b2 = -b0, b1 = 0) */
#define BP_A1     (-10714)
#define BP_A2       5673
#define AGC_ATT     5      /* peak tracker: attack 1/32 ...                 */
#define AGC_DEC     10     /* ... decay 1/1024 per sample                   */
#define PK_MIN      16
#define PLL_STEP    8192   /* 65536 per bit / 8 samples per bit             */
#define PLL_CTR     36864  /* transitions pulled to mid-bit + half a sample */
#define PLL_SHIFT   2      /* 1/4 of the error per transition               */
#define NSL         3      /* slicers                                       */
#define PRE_BITS    24u    /* busy for 3 bytes after two back-to-back flags */

/* ---- AX.25 ---- */
#define FRAME_MAX   330u   /* 10 addresses + control + PID + 256 info + FCS */
#define FRAME_MIN   18u    /* 2 addresses + control + PID + FCS              */
#define FCS_GOOD    0xF0B8u
#define HISTORY     5u

/* ---- Frequency list management ---- */
#define MAX_FREQ_ENTRIES   10u   /* max saved frequencies */
#define MAX_DESC_LEN       10u   /* max description length (10 chars) */
#define FREQ_CONFIG_VERSION 2u    /* config version for future compatibility */

/* ---- App version ---- */
#define APRSRX_VERSION "v1.1-F4IAE"  /* Version with F4IAE identifier */

typedef struct {
    uint16_t len;
    int16_t rssi;
    uint8_t buf[FRAME_MAX];
} frame_t;

/* Frequency list entry */
typedef struct {
    uint32_t freq_10hz;           /* frequency in 10 Hz units (144800000 = 144.800 MHz) */
    char     desc[MAX_DESC_LEN+1];/* user description (null-terminated) */
} freq_entry_t;

/* Frequency input buffer */
typedef struct {
    char     digits[10];         /* up to 9 digits + '\0' */
    uint8_t  pos;                 /* current cursor position */
    uint8_t  len;                 /* current length */
} freq_input_t;

/* the front end shared by the slicers */
typedef struct {
    int32_t  dc;                       /* DC tracker, Q4                          */
    int32_t  x1, x2, y1, y2;           /* band-pass state                         */
    int32_t  im, qm, is, qs;           /* sliding correlator sums                 */
    int32_t  pm, ps;                   /* per-tone magnitude peaks (AGC)          */
    uint32_t r, ks;                    /* ring slot = 1200 Hz phase, 2200 Hz phase;
                                          words: dem_t is inlined on the stack, where
                                          only words have an sp-relative load/store */
    int16_t  ring[8][4];               /* the products of the last bit            */
    int8_t   cm[8], cs[48];            /* cos tables (assets)                     */
} dem_t;
/* listen() loads both tables in one asset_read: they must stay back to back,
 * in the assets as in dem_t. */
_Static_assert(COS2200==COS1200+COS1200_LEN &&
               sizeof(((dem_t *)0)->cm)==COS1200_LEN &&
               sizeof(((dem_t *)0)->cs)==COS2200_LEN &&
               offsetof(dem_t,cs)==offsetof(dem_t,cm)+COS1200_LEN,
               "cos tables must stay contiguous");
_Static_assert(BIAS_CODE==2048u && offsetof(dem_t,pm)==36u &&
               offsetof(dem_t,ps)==40u &&
               offsetof(dem_t,cm)==DEMOD_INIT_LEN &&
               COS1200==DEMOD_INIT+DEMOD_INIT_LEN &&
               sizeof(dem_t)==DEMOD_INIT_LEN+COS1200_LEN+COS2200_LEN,
               "demodulator initialization asset must match dem_t");

/* one slicer: decision weights, DPLL, NRZI, HDLC */
typedef struct {
    int32_t  dprev, phase;             /* last decision, DPLL phase (65536/bit)   */
    uint16_t n, crc;                   /* bytes, running FCS                      */
    uint8_t  wa, wb, last;             /* mark/space weights, last level          */
    uint8_t  sr, ones, byte, nb;       /* HDLC: shift reg, 1 run, byte, bit count */
    uint8_t  inframe, hdr;             /* between flags, first bytes look like a call */
    uint8_t  bits;                     /* bits since the last flag                */
    bool     pre;                      /* this flag came right after another one  */
    uint8_t  buf[FRAME_MAX];
} sl_t;

/* The app state in one struct: a function loads one base address instead of one
 * literal-pool word per global. Bytes, then halfwords, then words, so every field
 * stays within the Thumb load/store immediate ranges (ldrb <= 31, ldrh <= 62,
 * ldr <= 124).
 * The loader zeroes the overlay (.bss) at every launch. */
static struct {
    uint8_t  prevKey, redraw;
    bool     running;
    uint8_t  count, cur;               /* history count, frame shown (0 = newest) */
    uint8_t  symTable, symCode;        /* symbol of the frame shown; table zero never
                                          matches an asset */
    uint8_t  cw, spk;                  /* the saved settings, in cfg order: view (0 scroll,
                                            CW_COMPACT compact), speaker amplifier on (key 1) */
    uint8_t  refresh;                  /* housekeeping slots since the last redraw */
    uint16_t vrow;                     /* y of the next body row before scrolling */
    uint16_t top, lim, nOk;            /* pixel scroll of the body, its limit, frames */
    const app_api_t *A;
    char *text;                        /* formatting buffer (app_main's stack)    */
    frame_t **history;                 /* newest first; buffers live on app_main's stack */
    uint32_t tFrame;                   /* ticks_ms of the last frame              */
    
    /* ---- Frequency list state ---- */
    freq_entry_t *freq_list;          /* pointer to stack-allocated list */
    uint8_t freq_count;                /* number of saved frequencies */
    uint8_t selected_index;            /* currently selected entry in menu */
    uint8_t edit_mode;                 /* 0=normal RX, 1=freq select, 2=freq edit, 3=desc edit */
    freq_input_t freq_input;           /* buffer for frequency input */
    char desc_input[MAX_DESC_LEN+1];   /* buffer for description input */
    uint8_t desc_cursor;               /* cursor position in description */
    bool list_dirty;                   /* unsaved changes flag */
} g;
#define str g.text

/* ---- tiny freestanding helpers: GCC may turn the zeroing / copy loops into calls ---- */
void *memset(void *d, int c, size_t n) {
    uint8_t *p = d; while (n) p[--n] = (uint8_t)c; return d;
}
void *memcpy(void *d, const void *s, size_t n) {
    uint8_t *p = d; const uint8_t *q = s;
    while (n) { --n; p[n] = q[n]; } return d;
}

/* ---- formatting ---- */
/* Share the string-copy loop across the display formatters. */
__attribute__((noinline))
static char *put(char *o,const char *s){ while(*s)*o++=*s++; return o; }
/* Formatting by repeated subtraction: no division. Values printed stay below 100000. */
static unsigned sub(uint32_t *v,uint32_t d){ unsigned q=0; while(*v>=d){ *v-=d; q++; } return q; }
/* The resident formatter (API level 3). One local stub keeps every call a
 * plain bl: the service lies past the ldr immediate range of the table. */
__attribute__((noinline))
static char *puti(char *o,int32_t v){ return g.A->append_i32(o,v); }
/* A tiny row holds 32 characters (4 px each): print_tiny does not clip, so
 * every row built below stays within that. */
static void tiny(uint8_t y,char *end){ *end='\0'; g.A->print_tiny(str,0,y,false,true); }

#define WAIT_CAPS_X 40u    /* "WAIT" capsule in the status bar, after the title */
#define SPK_X       59u    /* speaker icon (FoxHunt's, x = 59-68) after the capsule
                              (x <= 56), then the scroll marks at x = 72-76 as in APRS
                              TX, before the battery text (x >= 83): BMP_TAIL in the
                              assets, both in one read */

/* One frame at a time: its source in bold on line 0, its body scrolled under
 * it, y = 8 to 30, in one of two views (key *):
 * - normal (g.cw = 0): 18 characters per row, 8 px apart, 3 rows at rest;
 * - compact (g.cw = CW_COMPACT): 32 tiny characters per row, 6 px apart, 4 rows. */
#define ROW_CHARS   18u
#define CAPS_END    127u   /* last column of the capsules at the right of the
                              source (x >= 89 with "65535" and "2/5") */
#define CW_COMPACT  14u    /* compact rows: ROW_CHARS + 14 = 32 characters */

#define SYM_X 108u
/* The exact (table, code) pair first: E0 and YY have their own bitmap. An
 * overlay (table 0-9 or A-Z) without one then shows the alternate-table symbol
 * it is drawn over; the overlay character itself is in the body text. */
static void drawSymbol(void){
    const app_api_t *A=g.A;
    uint8_t hit[3];
    uint8_t t=g.symTable;
    for(;;){
        uint8_t slot=(uint8_t)((t+59u*g.symCode)&127u);
        A->asset_read((uint16_t)(SYM_MAP+slot*3u),hit,sizeof hit);
        if(hit[0] && hit[1]==t && hit[2]==g.symCode) break;
        if(t<'0' || t=='\\') return;          /* none, '/', or '\\' already tried */
        t='\\';
    }
    uint16_t off=(uint16_t)(SYM_BITMAPS+(uint16_t)(hit[0]-1u)*SYM_BYTES);
    for(uint8_t page=0;page<3u;page++)
        A->asset_read((uint16_t)(off+page*SYM_W),A->fb[4u+page]+SYM_X,SYM_W);
}

static bool callChar(uint8_t c){ return (c>='A'&&c<='Z')||(c>='0'&&c<='9')||c==' '; }

/* An APRS frame is a UI frame: the address field ends (bit 0 of an SSID byte)
 * and is followed by control 0x03 and PID 0xF0. Rejects the noise burst that
 * passes the 16-bit FCS about once a day in continuous decoding. */
static bool isUI(const uint8_t *f,uint16_t n){
    uint16_t end=(uint16_t)(n-2u), e=13;
    while(!(f[e]&1u) && e+7u<end) e+=7;
    return (f[e]&1u) && e+2u<end && f[e+1]==0x03u && f[e+2]==0xF0u;
}

