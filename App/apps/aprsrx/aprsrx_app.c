/* Draw frequency selection menu */
static void draw_freq_menu(void) {
    const app_api_t *A = g.A;
    char s[30];
    uint8_t y = 0;

    A->display_clear();
    A->status_clear();

    /* Title with version */
    A->print_inverse("APRS FREQ MENU " APRSRX_VERSION, 0, y, true, true, 128);
    y += 10;

    /* Draw list entries (max 4 visible at once) */
    uint8_t start_idx = g.selected_index < 2 ? 0 : g.selected_index - 1;
    if (start_idx > g.freq_count - 4 && g.freq_count >= 4) {
        start_idx = g.freq_count - 4;
    }
    
    for (uint8_t i = 0; i < 4 && i + start_idx < g.freq_count; i++) {
        uint8_t entry_idx = i + start_idx;
        freq_entry_t *entry = &g.freq_list[entry_idx];
        uint8_t line = y + i * 10;
        
        if (entry_idx == g.selected_index) {
            /* Highlight selected entry */
            A->print_inverse(entry->desc, 0, line, false, true, 128);
        } else {
            A->print_normal(entry->desc, 0, line, 4);
        }
        
        /* Frequency on the right */
        format_frequency(s, entry->freq_10hz);
        A->print_normal(s, 60, line, 4);
    }

    /* Indicate if there are more entries above/below */
    if (g.freq_count > 4) {
        if (start_idx > 0) {
            A->print_tiny("^", 0, y + 4 * 10, false, false);
        }
        if (start_idx + 4 < g.freq_count) {
            A->print_tiny("v", 0, y + 4 * 10, false, false);
        }
    }

    /* Instructions at the bottom */
    if (g.edit_mode == 1) { /* SELECT mode */
        if (g.freq_count > 0) {
            A->print_tiny("F=new *apply", 0, 55, false, false);
            A->print_tiny("2=del 1=save", 60, 55, false, false);
        } else {
            A->print_tiny("F=new  EXIT=back", 0, 55, false, false);
        }
    } else if (g.edit_mode == 2) { /* EDIT_FREQ mode */
        A->print_tiny("Enter freq (MHz):", 0, 55, false, false);
        A->print_tiny(g.freq_input.digits, 0, 63, false, false);
    } else if (g.edit_mode == 3) { /* EDIT_DESC mode */
        A->print_tiny("Enter desc:", 0, 55, false, false);
        A->print_tiny(g.desc_input, 0, 63, false, false);
        /* Show cursor position */
        if (g.desc_cursor < MAX_DESC_LEN && g.desc_input[g.desc_cursor] != '\0') {
            /* Simple cursor indicator */
            uint8_t x_pos = g.desc_cursor * 6;
            if (x_pos < 128) {
                A->fb[63][x_pos] ^= 0xFF; /* Invert pixel at cursor */
            }
        }
    }

    A->blit_full();
    A->blit_status();
}

